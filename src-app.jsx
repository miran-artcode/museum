function StudentApp({ me, onExit, onGallery }) {
  const WSKEY = "ws:" + me.sid;
  const [ws, setWs] = useState({});
  const [loaded, setLoaded] = useState(false);
  const [openMap, setOpenMap] = useState(DEFAULT_OPEN);
  const [tab, setTab] = useState(SESSIONS[0]);
  useEffect(() => { if (loaded && !isOpen(openMap, tab)) { const first = SESSIONS.find((s) => isOpen(openMap, s)); if (first) setTab(first); } }, [loaded, openMap]);
  const [saveState, setSaveState] = useState("saved"); // saved | dirty | saving | err
  const [savedAt, setSavedAt] = useState(null);
  const [grade, setGrade] = useState(null);
  const timer = useRef(null);
  const retryTimer = useRef(null);
  const wsRef = useRef(ws);
  const dirtyRef = useRef(false);
  const savingRef = useRef(false);
  wsRef.current = ws;

  useEffect(() => {
    setMediaOwner(me.sid);
    (async () => {
      const saved = await store.get(WSKEY);
      if (saved) { setWs(saved); setSavedAt(saved._updatedAt || null); }
      setGrade(await store.get("grade:" + me.sid));
      const cfg = await store.get("config");
      setOpenMap((cfg && cfg.open) || DEFAULT_OPEN);
      setLoaded(true);
    })();
  }, []);

  // 차시 공개 설정과 교사 피드백을 실시간으로 받음
  useEffect(() => {
    const un1 = fbStore.watchDoc("config", (cfg) => { if (cfg && cfg.open) setOpenMap(cfg.open); });
    const un2 = fbStore.watchDoc("grade:" + me.sid, (g) => { if (g) setGrade(g); });
    return () => { un1(); un2(); };
  }, []);

  const doSave = async () => {
    if (savingRef.current) return;
    savingRef.current = true;
    dirtyRef.current = false;
    setSaveState("saving");
    const data = { ...wsRef.current, _updatedAt: now() };
    const ok = await store.set(WSKEY, data);
    savingRef.current = false;
    if (ok) {
      setSavedAt(data._updatedAt);
      if (dirtyRef.current) { setSaveState("dirty"); doSave(); }
      else setSaveState("saved");
    } else {
      dirtyRef.current = true;
      setSaveState("err");
      if (retryTimer.current) clearTimeout(retryTimer.current);
      retryTimer.current = setTimeout(doSave, 5000); // 실패 시 5초 뒤 자동 재시도
    }
  };

  const flush = () => {
    if (timer.current) clearTimeout(timer.current);
    if (dirtyRef.current || saveState === "dirty") doSave();
  };

  const setField = (k, v) => {
    if (!loaded) return;
    setWs((p) => {
      const next = { ...p, [k]: v };
      // 사고 변화를 볼 자리는 고쳐 쓰기 전의 문장을 남겨 둠
      if (TRACKED.includes(k) && typeof p[k] === "string" && typeof v === "string") {
        const prev = p[k].trim();
        const log = p._log || [];
        const last = log.filter((e) => e.k === k).slice(-1)[0];
        const gapOk = !last || Date.now() - new Date(last.at).getTime() > 120000;
        if (prev.length > 15 && gapOk && Math.abs(v.trim().length - prev.length) > 8) {
          next._log = [...log, { k, at: now(), prev: prev.slice(0, 400) }].slice(-120);
        }
      }
      const t = { ...(p._t || {}) };
      const sid = String(k).split(".")[0];
      t[sid] = { first: (t[sid] && t[sid].first) || now(), last: now(), edits: ((t[sid] && t[sid].edits) || 0) + 1 };
      next._t = t;
      return next;
    });
    dirtyRef.current = true;
    setSaveState("dirty");
    if (timer.current) clearTimeout(timer.current);
    timer.current = setTimeout(doSave, 600); // 입력이 멈추면 0.6초 안에 저장
  };

  useEffect(() => {
    const onHide = () => { if (document.visibilityState === "hidden") flush(); };
    window.addEventListener("visibilitychange", onHide);
    window.addEventListener("pagehide", flush);
    window.addEventListener("blur", flush);
    return () => {
      window.removeEventListener("visibilitychange", onHide);
      window.removeEventListener("pagehide", flush);
      window.removeEventListener("blur", flush);
      if (timer.current) clearTimeout(timer.current);
      if (retryTimer.current) clearTimeout(retryTimer.current);
    };
  }, []);

  const switchTab = (s) => { flush(); setTab(s); };

  const pct = overallProgress(ws);
  const secs = SCHEMA.filter((s) => s.session === tab);

  return (
    <div>
      <div className="topbar">
        <div className="topbar-in">
          <div className="brand">허구의 아카이브 기록실<small>STUDENT · {me.sid}</small></div>
          <div className="top-right">
            <span>{me.nick}</span>
            <span className={"save-pill " + (saveState === "dirty" || saveState === "saving" ? "dirty" : saveState === "err" ? "err" : "")}>
              {saveState === "saving" ? "저장 중…" : saveState === "dirty" ? "입력 중…" : saveState === "err" ? "저장 실패 — 5초 뒤 재시도" : "저장됨 " + fmtTime(savedAt)}
            </span>
            {saveState === "err" && <button className="btn small" onClick={doSave}>지금 저장</button>}
            <button className="btn small ghost" onClick={onGallery}>전시장</button>
            <button className="btn small ghost" onClick={async () => { await doSave(); await authApi.leave(); onExit(); }}>나가기</button>
          </div>
        </div>
      </div>
      <div className="wrap">
        <div className="prog-strip">
          <ProgressBar pct={pct} />
          <span className="prog-num">{pct}%</span>
          <span className="prog-num">미디어 {mediaCount(ws)}건</span>
        </div>
        <div className="sess-tabs" role="tablist">
          {SESSIONS.map((s) => {
            const open = isOpen(openMap, s);
            return (
              <button key={s} className={"sess-tab " + (tab === s ? "on" : "") + (open ? "" : " locked")}
                onClick={() => open && switchTab(s)} disabled={!open} title={open ? s : s + " 잠김"}>
                {open ? <SessionDot ratio={sessionProgress(s, ws)} /> : <span className="lock">잠김</span>}{s}
              </button>
            );
          })}
        </div>

        {grade && (filled(grade.fbForm) || filled(grade.fbConcept)) && (
          <div className="feedback-card">
            <h3>선생님의 피드백</h3>
            {filled(grade.fbForm) && <p>조형 기준 질문 — {grade.fbForm}</p>}
            {filled(grade.fbConcept) && <p style={{ marginTop: 6 }}>작품 개념 질문 — {grade.fbConcept}</p>}
          </div>
        )}

        {!isOpen(openMap, tab) ? (
          <div className="card"><div className="card-body" style={{ color: "var(--sub)", fontSize: 13 }}>
            이 차시는 아직 열리지 않았습니다. 선생님이 수업 시간에 열어 주면 강의 노트와 학습지가 나타납니다.
          </div></div>
        ) : null}
        {isOpen(openMap, tab) && LESSONS.filter((L) => L.session === tab).map((L) => {
          const confirmSec = secs.find((s) => s.id === "l" + L.n);
          const inquirySec = secs.find((s) => s.id === "q" + L.n);
          return (
            <React.Fragment key={L.n}>
              <LessonPanel L={L} />
              {confirmSec && <SectionCard sec={confirmSec} ws={ws} setField={setField} />}
              {inquirySec && <SectionCard sec={inquirySec} ws={ws} setField={setField} />}
            </React.Fragment>
          );
        })}
        {isOpen(openMap, tab) && secs.filter((s) => s.kind !== "learn" && s.kind !== "inquiry").map((sec) => (
          <SectionCard key={sec.id} sec={sec} ws={ws} setField={setField} />
        ))}
      </div>
    </div>
  );
}

