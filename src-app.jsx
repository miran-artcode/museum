/* 차시 공개 설정: 교사가 열어 준 차시만 학생 화면에 나타남 */
const DEFAULT_OPEN = { "1차시": true };
function isOpen(openMap, s) {
  const m = openMap || DEFAULT_OPEN;
  return m[s] === true;
}

/* ---------- 진행률 계산 ---------- */
const filled = (v) => typeof v === "string" && v.trim().length > 0;

function sectionProgress(sec, ws) {
  const d = ws || {};
  let total = 0, done = 0;
  for (const f of sec.fields) {
    if (f.opt) continue;
    const v = d[sec.id + "." + f.k];
    if (f.t === "toggle") {
      total += 1;
      if (filled(v)) done += 1;
    } else if (f.t === "debate") {
      total += 3;
      const m = v || {};
      ["pos", "counter", "hold"].forEach((k2) => { if (filled(m[k2])) done += 1; });
    } else if (f.t === "reflect") {
      total += 1;
      if (filled((v || {}).pos)) done += 1;
    } else if (f.t === "rounds") {
      total += 1;
      const rows = v || [];
      if (rows.some((r) => r && (filled(r.tool) || filled(r.judge)))) done += 1;
    } else if (f.t === "inspect") {
      total += INSPECT_ITEMS.length;
      const m = v || {};
      done += INSPECT_ITEMS.filter((it) => m[it.k] && m[it.k].status).length;
    } else if (f.t === "checks") {
      total += 1;
      const m = v || {};
      if (f.opts.some((o) => m[o])) done += 1;
    } else if (f.t === "peer") {
      total += 2;
      const p = v || [{}, {}];
      p.slice(0, 2).forEach((b) => { if (b && (filled(b.no) || filled(b.overall))) done += 1; });
    } else {
      total += 1;
      if (filled(v)) done += 1;
    }
  }
  return { total, done };
}

function overallProgress(ws) {
  let t = 0, d = 0;
  for (const sec of SCHEMA) { const p = sectionProgress(sec, ws); t += p.total; d += p.done; }
  return t ? Math.round((d / t) * 100) : 0;
}

function sessionProgress(session, ws) {
  let t = 0, d = 0;
  for (const sec of SCHEMA.filter((s) => s.session === session)) {
    const p = sectionProgress(sec, ws); t += p.total; d += p.done;
  }
  return t ? d / t : 0;
}

