/* 멀티모달 자료 목록 — 기록지 안의 사진·음성 필드를 모아 둠 */

function mediaFields() {
  const out = [];
  for (const sec of SCHEMA) {
    for (const f of sec.fields) {
      if (f.t === "image" || f.t === "images" || f.t === "audio" || f.t === "sketch" || f.t === "video") out.push({ sec, f, key: sec.id + "." + f.k });
    }
  }
  return out;
}

function mediaCount(ws) {
  const d = ws || {};
  let n = 0;
  for (const m of mediaFields()) {
    const v = d[m.key];
    if (!v) continue;
    n += Array.isArray(v) ? v.length : 1;
  }
  const rounds = d["s5b.rounds"] || [];
  n += rounds.filter((r) => r && r.img).length;
  return n;
}

